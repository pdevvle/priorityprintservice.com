// Builds pps-zip-city.php — the free ZIP → city table behind the address hint.
//
// Source: GeoNames US postal codes (https://download.geonames.org/export/zip/US.zip),
// Creative Commons Attribution 4.0 — credit "GeoNames, www.geonames.org". One primary
// place name per ZIP; the post office accepts others (Hollywood for 90046, New River for
// 85086), so the plugin accepts any city found anywhere in the same three-digit ZIP area
// and only ever HINTS, never asks or refuses.
//
// Output is a PHP file returning an array, so opcache keeps it in shared memory and a
// lookup costs nothing per request:
//   'c' => list of city names (upper case), 'z' => [zip5 => city index],
//   'p' => [zip3 => list of city indexes seen in that area]
//
// Run: node tools-build-zip-city.mjs <path to US.txt> > pps-zip-city.php
import { readFileSync } from 'node:fs';

const src = process.argv[2];
if (!src) { console.error('usage: node tools-build-zip-city.mjs <US.txt>'); process.exit(1); }
const rows = readFileSync(src, 'utf8').split('\n').filter(Boolean).map(l => l.split('\t'));
const cities = [], idx = new Map(), z = {}, p = {};
for (const r of rows) {
  const zip = (r[1] || '').trim(), name = (r[2] || '').trim().toUpperCase(), st = (r[4] || '').trim().toUpperCase();
  if (!/^\d{5}$/.test(zip) || !name) continue;
  const key = name + '|' + st;
  if (!idx.has(key)) { idx.set(key, cities.length); cities.push(key); }
  const i = idx.get(key);
  if (z[zip] === undefined) z[zip] = i;
  const z3 = zip.slice(0, 3);
  (p[z3] = p[z3] || new Set()).add(i);
}
const esc = s => "'" + s.replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
let out = "<?php\n// GENERATED by tools-build-zip-city.mjs from GeoNames US postal codes (CC BY 4.0,\n// www.geonames.org). Do not edit; rebuild. " + Object.keys(z).length + ' ZIPs, ' + cities.length + " places.\n";
out += "if ( ! defined( 'ABSPATH' ) && ! defined( 'PPS_TEST' ) ) exit;\nreturn array(\n'c'=>array(" + cities.map(esc).join(',') + "),\n'z'=>array(";
out += Object.keys(z).sort().map(k => "'" + k + "'=>" + z[k]).join(',') + "),\n'p'=>array(";
out += Object.keys(p).sort().map(k => "'" + k + "'=>array(" + [...p[k]].join(',') + ')').join(',') + "),\n);\n";
process.stdout.write(out);
